# GROUP BY – Деректерді топтастыру

# Білесің бе, кейде бірдей мәндерді бір топқа жинап, оларды санап немесе талдап шыққың келеді.
# Мысалы, компаниядағы әр жыныстағы қызметкерлер санын немесе олардың орташа жасын білгің келсе, GROUP BY көмектеседі.
# Кеттік, практикада көрейік! 

# 1. Былай жасасаң, employee_demographics кестесіндегі барлық ақпаратты көресің:
SELECT * 
FROM employee_demographics;

# 2. Ал енді, осы кестедегі қызметкерлерді жынысына (gender) қарай топтастырып көрейік.
# Яғни, ерлер бөлек, әйелдер бөлек болады, бірақ әзірге тек олардың жынысы көрсетіледі:
SELECT gender
FROM employee_demographics
GROUP BY gender;

# 3. Ал енді бұны сәл қызықтырақ етейік. Әр жыныс тобы бойынша орташа жасын (AVG) есептеп шығарайық:
# Осылайша, "Еркектердің орташа жасы - 41.2857, Әйелдердің орташа жасы - 38.5" дегендей дерек аласың.
SELECT gender, AVG(age)
FROM employee_demographics
GROUP BY gender;

# 4. Мынаны енді нағыз деректер талдауы деп айтуға болады!
# Әр жыныс үшін:
# - Орташа жас (AVG)
# - Ең үлкен жас (MAX)
# - Ең кіші жас (MIN)
# - Сол топтағы адамдар саны (COUNT)
# Қызметкерлер туралы тереңірек ақпарат аласың! 

SELECT gender, AVG(age), MAX(age), MIN(age), COUNT(age)
FROM employee_demographics
GROUP BY gender;


/* ORDER BY – Деректерді реттеу
 GROUP BY деректерді топтастырса, ORDER BY оларды реттеуге көмектеседі.
 Қарапайым мысалдармен көрейік! 🎯
*/

# 5. Бұл сұраныс қызметкерлерді first_name (аты) бойынша әліпби ретімен (A-Я) орналастырады.
SELECT *
FROM employee_demographics
ORDER BY first_name; # ASC (ASC деп көрсетпесең де, өздігінен солай қабылданыды)
/*
 ASC (Ascending – Өсу реті) → Кіші мәннен үлкенге қарай реттейді.
Мәтіндер (A → Z)
Сандар (1 → 100)
Күндер (Ескі → Жаңа)
*/

# 6. Ал енді керісінше, аттарды Я-A бағытында реттеп көрейік.
SELECT *
FROM employee_demographics
ORDER BY first_name DESC;
/*
DESC (Descending – Кему реті) → Үлкен мәннен кішіге қарай реттейді.
Мәтіндер (Z → A)
Сандар (100 → 1)
Күндер (Жаңа → Ескі)
*/

# 7. Егер бірден екі баған бойынша реттегің келсе ше? Мысалы:
# - Алдымен gender (жынысы) бойынша (Әйелдер бірінші, Ерлер кейін).
# - Бірдей жыныстағылар болса, олардың жасын (age) кішіден үлкенге қарай орналастыру.
SELECT *
FROM employee_demographics
ORDER BY gender, age;

# 8. Сен ORDER BY баған атын жазбай-ақ, баған нөмірі арқылы да реттей аласың.
# Төмендегі сұраныс 5-ші баған (gender) және 4-ші баған (age) бойынша реттейді.
SELECT *
FROM employee_demographics
ORDER BY 5, 4; # Аналог ORDER BY gender, age

# Қорытынды: 
# - GROUP BY → деректерді топтастырады.
# - ORDER BY → оларды реттейді.
