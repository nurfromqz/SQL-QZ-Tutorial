# WHERE шарт операторы

# WHERE операторы SQL-дің негізгі мүмкіндіктерінің бірі болып табылады.
# Ол тек белгілі бір шарттарға сәйкес келетін жолдарды (жазбаларды) таңдау үшін қолданылады.
# Төмендегі сұраныстар арқылы WHERE операторының қалай жұмыс істейтінін түсінейік.

# 1. Бұл сұраныс employee_salary кестесінен first_name мәні 'Лесли' болатын жазбаларды қайтарады.
# Яғни, тек есімі "Лесли" болған қызметкер туралы ақпаратты көрсетеді.
SELECT * FROM employee_salary
WHERE first_name = 'Лесли';

# 2. Бұл сұраныс жалақысы 50 000-нан жоғары қызметкерлерді шығарады.
# Мысалы, жалақысы 60 000 немесе 80 000 болған қызметкерлер көрініп, 45 000 алғандар көрінбейді.
SELECT *
FROM employee_salary
WHERE salary > 50000;

# 3. Бұл сұраныс жалақысы 50 000-ға тең немесе одан жоғары қызметкерлерді қайтарады.
# Егер біреу 50 000 алатын болса, ол да нәтижеге кіреді.
SELECT *
FROM employee_salary
WHERE salary >= 50000;

# 4. Бұл сұраныс жалақысы 50 000-нан төмен қызметкерлерді қайтарады.
# Яғни, тек 49 999 немесе одан аз жалақы алатын адамдарды көрсетеді.
SELECT *
FROM employee_salary
WHERE salary < 50000;

# 5. Бұл сұраныс employee_demographics кестесінен тек әйел қызметкерлерді қайтарады.
# gender бағанында "Әйел" деп жазылған жолдар ғана көрсетіледі.
SELECT * 
FROM employee_demographics
WHERE gender = 'Әйел';

# 6. Бұл сұраныс employee_demographics кестесінен әйел емес қызметкерлерді шығарады.
# Яғни, gender бағанында "Әйел" емес, басқа мәндер бар адамдар көрсетіледі (мысалы, "Еркек").
SELECT * 
FROM employee_demographics
WHERE gender != 'Әйел';

# 7. Бұл сұраныс туған күні 1985 жылдың 1 қаңтарынан кейінгі қызметкерлерді көрсетеді.
# Мысалы, 1986, 1990 немесе 2000 жылы туған қызметкерлер көрінеді.
SELECT * 
FROM employee_demographics
WHERE birth_date > '1985-01-01';


# AND, OR, NOT - Логикалық операторлар

# Логикалық операторлар SQL-де бірнеше шартты біріктіруге мүмкіндік береді.
# Бұл операторлар деректерді сүзуді нақтылай түседі.

# 8. Бұл сұраныс екі шартты біріктіреді:
# - туған күні 1985 жылдың 1 қаңтарынан кейін болғандар
# - немесе жынысы "male" (ер адам) болғандар көрсетіледі.
SELECT * FROM employee_demographics
WHERE birth_date > '1985-01-01'
OR gender = 'male';

# 9. Бұл сұраныс екі шартты бір уақытта тексереді:
# - first_name 'Лесли' болуы керек
# - жасы 44-ке тең болуы керек
# Егер бір шарт орындалмаса, нәтиже шықпайды.
SELECT * FROM employee_demographics
WHERE first_name = 'Лесли' AND age = 44;

# 10. Бұл сұраныс сәл күрделірек:
# - first_name "Лесли" және жасы 44 болса, нәтиже шығады
# - немесе жасы 55 болса, да нәтиже шығады
# Яғни, 44 жастағы Лесли немесе 55 жастағы кез келген адам шығады.
SELECT * FROM employee_demographics
WHERE (first_name = 'Лесли' AND age = 44) OR age = 55;


# LIKE операторы
# LIKE - мәтіндік мәндерді белгілі бір үлгі бойынша іздеу үшін қолданылады.
# Бұл операторда % және _ арнайы таңбалары қолданылады.

# 11. Бұл сұраныс first_name бағанында соңғы әріптері "нна" болатын адамдарды көрсетеді.
# Мысалы, "Анна", "Жанна" сияқты аттар нәтиже ретінде шығады.
SELECT * 
FROM employee_demographics
WHERE first_name LIKE '%нна';

# 12. Бұл сұраныс ішінде "рей" әріптер жиынтығы кездесетін first_name мәндерін қайтарады.
# Мысалы, "Андрей", "Грейс" сияқты есімдер сәйкес келеді.
SELECT * FROM employee_demographics
WHERE first_name LIKE '%рей%';

# 13. Бұл сұраныс "э" әрпінен басталып, үшінші символдан кейін кез келген жалғасатын first_name мәндерін қайтарады.
# Элис, Эржан, Эльмира сияқты есімдер сәйкес келуі мүмкін.
SELECT * FROM employee_demographics
WHERE first_name LIKE 'э__%';

# 14. Бұл сұраныс 1962 жылы туған қызметкерлерді қайтарады.
# Себебі birth_date бағанындағы мәндер "1962" жылымен басталатын жазбаларды ғана көрсетеді.
SELECT * FROM employee_demographics
WHERE birth_date LIKE '1962%';
