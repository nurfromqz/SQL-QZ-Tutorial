DISTINCT — Бұл кілттік сөз қайталанатын мәндерді алып тастау үшін қолданылады. Яғни, біз тек әртүрлі мәндерді ғана аламыз. Бұл сұраныс тек бірегей gender мәндерін (жыныс) қайтарады, қайталанатын мәндер көрсетілмейді.
#gender — Бұл employee_demographics кестесіндегі жыныс атрибуты. Бұл сұраныс бізге қызметкерлердің тек бірегей жыныс мәндерін көрсету үшін қажет.
#FROM employee_demographics — Бұл біз деректерді қайдан алатынымызды көрсетеді. Яғни, сұраныс employee_demographics кестесінен мәлімет алатын болады.
#Қорытындысында, осы сұраныс employee_demographics кестесінен қызметкерлердің тек әртүрлі жыныс мәндерін қайтарады. Мысалы, егер кестеде бірнеше рет "Еркек" және "Әйел" мәндері болса, сұраныс #оларды тек бір рет көрсетеді. */



/*
SQL-де арифметикалық операциялар PEMDAS (Parentheses, Exponents, Multiplication and Division, Addition and Subtraction) реттілігіне сәйкес орындалады, яғни бұл реттілік кез келген математикалық есептеулерде қолданылатын стандартты ереже. Осы реттілікті түсіну өте маңызды, себебі ол есептеулердің нәтижесін дұрыс алу үшін қажет.

PEMDAS реттілігі:

P (Parentheses) — Дөңгелек жақшалар: Бірінші кезекте жақшалар ішіндегі операциялар орындалады.
E (Exponents) — Степень (күшейту): Содан кейін степендтер (күшейту операциясы) орындалады.
MD (Multiplication and Division) — Көбейту және бөлу: Көбейту мен бөлу операциялары бірдей дәрежеде орындалады, бірақ солдан оңға қарай.
AS (Addition and Subtraction) — Қосу және алу: Қосу мен алу операциялары да бірдей дәрежеде орындалады, солдан оңға қарай.
*/
#Қарапайым SQL сұранысын қарастырайық:
SELECT 5 + 2 * 3;
/*
Бұл сұраныс PEMDAS реттілігі бойынша былай орындалады:
Алдымен көбейту (2 * 3) орындалады, нәтижесі 6 болады.
Содан кейін қосу (5 + 6) орындалады, нәтижесі 11 болады.
Яғни, бұл сұраныстың нәтижесі 11 болады.
*/


#Тағы бір мысал:
SELECT (5 + 2) * 3;
/*
Бұл сұраныс үшін PEMDAS реттілігі:
Алдымен жақшалар ішіндегі операция орындалады: (5 + 2) = 7.
Содан кейін көбейту (7 * 3) орындалады, нәтижесі 21 болады.
Яғни, бұл сұраныстың нәтижесі 21 болады.
*/

#Күрделі мысал:
SELECT 5 + 2 * 3 - 4 / 2;
/*Бұл сұраныс үшін орындалу реттілігі:
Көбейту (2 * 3) = 6.
Бөлу (4 / 2) = 2.
Қосу (5 + 6) = 11.
Алу (11 - 2) = 9.
Нәтиже: 9.*/
